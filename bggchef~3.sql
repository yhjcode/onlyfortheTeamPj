CREATE TABLE RECIPE_STEP (STEP_ID NUMBER(20,0), RECIPE_ID NUMBER(20,0) NOT NULL, STEP_NO NUMBER(5,0) NOT NULL, IMAGE_URL VARCHAR2(500), CONTENT CLOB NOT NULL, PRIMARY KEY (STEP_ID), CONSTRAINT FK_STEP_RECIPE FOREIGN KEY (RECIPE_ID) REFERENCES RECIPE (RECIPE_ID) ON DELETE CASCADE);
CREATE TABLE RECOMMENDED_THEME (THEME_ID NUMBER(11,0), USER_ID VARCHAR2(20) NOT NULL, TITLE VARCHAR2(100) NOT NULL, DESCRIPTION CLOB, THUMBNAIL VARCHAR2(500), LINK_URL VARCHAR2(500), IS_VISIBLE NUMBER(1,0) DEFAULT 1 NOT NULL, VIEW_COUNT NUMBER(11,0) DEFAULT 0 NOT NULL, CREATED_AT DATE DEFAULT SYSDATE NOT NULL, SUBTITLE VARCHAR2(200), PRIMARY KEY (THEME_ID), CONSTRAINT FK_THEME_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID));
CREATE TABLE RECIPE_LIKE (RECIPE_ID NUMBER(20,0) NOT NULL, USER_ID VARCHAR2(20) NOT NULL, CREATED_AT DATE DEFAULT SYSDATE NOT NULL, PRIMARY KEY (RECIPE_ID, USER_ID), CONSTRAINT FK_LIKE_RECIPE FOREIGN KEY (RECIPE_ID) REFERENCES RECIPE (RECIPE_ID), CONSTRAINT FK_LIKE_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID));
CREATE TABLE FAVORITE (FAVORITE_ID NUMBER(20,0), USER_ID VARCHAR2(20) NOT NULL, RECIPE_ID NUMBER(20,0) NOT NULL, CREATED_AT DATE DEFAULT SYSDATE NOT NULL, PRIMARY KEY (FAVORITE_ID), CONSTRAINT UQ_FAVORITE UNIQUE (USER_ID, RECIPE_ID), CONSTRAINT FK_FAV_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID), CONSTRAINT FK_FAV_RECIPE FOREIGN KEY (RECIPE_ID) REFERENCES RECIPE (RECIPE_ID));
CREATE TABLE THEME_RECIPE (THEME_RECIPE_ID NUMBER(20,0), THEME_ID NUMBER(11,0) NOT NULL, RECIPE_ID NUMBER(20,0) NOT NULL, SORT_ORDER NUMBER(5,0), USER_ID VARCHAR2(20), DESCRIPTION VARCHAR2(1000), PRIMARY KEY (THEME_RECIPE_ID), CONSTRAINT UQ_THEME_RECIPE UNIQUE (THEME_ID, RECIPE_ID), CONSTRAINT FK_TR_THEME FOREIGN KEY (THEME_ID) REFERENCES RECOMMENDED_THEME (THEME_ID) ON DELETE CASCADE, CONSTRAINT FK_TR_RECIPE FOREIGN KEY (RECIPE_ID) REFERENCES RECIPE (RECIPE_ID));
