CREATE TABLE RECIPE (RECIPE_ID NUMBER(20,0), USER_ID VARCHAR2(20) NOT NULL, CATEGORY_ID NUMBER(11,0) NOT NULL, TITLE VARCHAR2(200) NOT NULL, THUMBNAIL VARCHAR2(500), DESCRIPTION CLOB, SERVINGS NUMBER(5,0) NOT NULL, COOK_TIME NUMBER(5,0) NOT NULL, DIFFICULTY NUMBER(1,0) NOT NULL, VIEW_COUNT NUMBER(11,0) DEFAULT 0 NOT NULL, AVG_RATING NUMBER(3,1), IS_DELETED NUMBER(1,0) DEFAULT 0 NOT NULL, CREATED_AT DATE DEFAULT SYSDATE NOT NULL, LINK VARCHAR2(500), CONSTRAINT CK_RECIPE_DIFF CHECK (DIFFICULTY IN (1,2,3)), PRIMARY KEY (RECIPE_ID), CONSTRAINT FK_RECIPE_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID), CONSTRAINT FK_RECIPE_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY_M (CATEGORYM_ID));
